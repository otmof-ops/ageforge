"""Generate src/tables.rs from the Python engine's tables, so the two engines share one source of truth.
Run from core/: python3 gen_tables.py (bin/build-core runs it before building)."""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from realm_of_ages import data, geography, resources  # noqa: E402


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def f(x):
    x = float(x)
    return repr(x) if "." in repr(x) or "e" in repr(x) else repr(x) + ".0"


out = ["//! Generated by gen_tables.py from the Python engine's tables. Do not edit by hand.", "#![allow(dead_code)]", ""]


def strs(name, xs):
    out.append(f"pub const {name}: [&str; {len(xs)}] = [{', '.join(rs_str(x) for x in xs)}];")


def nums(name, xs, ty="f64"):
    vals = ", ".join(f(x) if ty == "f64" else str(int(x)) for x in xs)
    out.append(f"pub const {name}: [{ty}; {len(xs)}] = [{vals}];")


def grid(name, rows):
    rows = [list(r) for r in rows]
    inner = ", ".join("[" + ", ".join(f(x) for x in r) + "]" for r in rows)
    out.append(f"pub const {name}: [[f64; {len(rows[0])}]; {len(rows)}] = [{inner}];")


def syl(name, d):
    """{people: (list, list, ...)} -> [[&[&str]; k]; 4]"""
    parts = []
    for p in range(4):
        groups = d[p]
        parts.append("[" + ", ".join("&[" + ", ".join(rs_str(s) for s in g) + "]" for g in groups) + "]")
    k = len(d[0])
    out.append(f"pub const {name}: [[&[&str]; {k}]; 4] = [{', '.join(parts)}];")


# land
out.append("pub const OCEAN: i8 = 0; pub const PLAINS: i8 = 1; pub const FOREST: i8 = 2; pub const HILLS: i8 = 3;")
out.append("pub const MOUNTAIN: i8 = 4; pub const SWAMP: i8 = 5; pub const DESERT: i8 = 6;")
strs("PEOPLES", data.PEOPLES); strs("ADJ", data.ADJ); strs("SINGULAR", data.SINGULAR)
grid("FOOD", data.FOOD); grid("WEALTH", data.WEALTH); grid("BASE_REL", data.BASE_REL)
for n in ("GROWTH", "MARTIAL", "MAGIC", "DEFENSE", "AGGRESSION", "SETTLE_AT", "LIFESPAN", "ADULT", "FERTILE_END",
          "FERTILITY", "TALENT_BASE", "PROWESS_BASE", "TIER_CAP", "PROWESS_CAP", "STORY"):
    nums(n, getattr(data, n))
strs("REALM_STYLE", data.REALM_STYLE)
strs("RULER_TITLE_M", [a for a, _ in data.RULER_TITLE]); strs("RULER_TITLE_F", [b for _, b in data.RULER_TITLE])
strs("HOUSE_STYLE", data.HOUSE_STYLE)
# names
syl("TOWN_SYL", data.TOWN_SYL); syl("FIRST", data.FIRST)
strs("LAND_A", geography.LAND_A); strs("LAND_B", geography.LAND_B); strs("ISLE_A", geography.ISLE_A)
strs("SEA_A", geography.SEA_A)
# resources: name, kind, terrains (as codes; -1 coast, -2 mana, -3 grove), chance, effect
codes = {"coast": -1, "mana": -2, "grove": -3}
res = []
for name, (kind, terr, p, col, fx) in resources.RESOURCES.items():
    ts = ", ".join(str(codes.get(t, t)) for t in terr)
    res.append(f"Res {{ name: {rs_str(name)}, kind: {rs_str(kind)}, terrains: &[{ts}], chance: {f(p)}, "
               f"effect: {rs_str(fx)} }}")
out.append("pub struct Res { pub name: &'static str, pub kind: &'static str, pub terrains: &'static [i32], "
           "pub chance: f64, pub effect: &'static str }")
out.append(f"pub const RESOURCES: [Res; {len(res)}] = [{', '.join(res)}];")


# ---- characters: classes (base then prestige), traits, attributes, skills, legacies
from realm_of_ages import data2  # noqa: E402
FX_KEYS = ["phys", "magic", "hp", "war", "guard", "vs_monster", "delve", "equip", "tier", "lead", "intrigue"]
out.append(f"pub const FX_KEYS: [&str; {len(FX_KEYS)}] = [{', '.join(rs_str(k) for k in FX_KEYS)}];")
classes = list(data.CLASSES) + list(data.PRESTIGE)
out.append("pub struct Class { pub name: &'static str, pub phys: f64, pub magic: f64, pub school: i8, pub hp: f64, "
           "pub prestige: bool, pub branches: [(&'static str, usize, [&'static str; 4]); 3], "
           "pub capstone: &'static str, pub fx: &'static [(usize, f64)] }")
rows = []
for n in classes:
    if n in data.CLASSES:
        d = data.CLASSES[n]
        br = ", ".join(f"({rs_str(b)}, {FX_KEYS.index(k)}, [{', '.join(rs_str(x) for x in sk)}])"
                       for b, k, sk in d["branches"])
        cap, fx = d["capstone"]
        school = -1 if d["school"] is None else d["school"]
        rows.append(f"Class {{ name: {rs_str(n)}, phys: {f(d['phys'])}, magic: {f(d['magic'])}, school: {school}, "
                    f"hp: {f(d['hp'])}, prestige: false, branches: [{br}], capstone: {rs_str(cap)}, "
                    f"fx: &[{', '.join(f'({FX_KEYS.index(k)}, {f(v)})' for k, v in fx.items())}] }}")
    else:
        d = data.PRESTIGE[n]
        empty = '("", 0, ["", "", "", ""])'
        rows.append(f"Class {{ name: {rs_str(n)}, phys: {f(d['phys'])}, magic: {f(d['magic'])}, school: -1, "
                    f"hp: {f(d['hp'])}, prestige: true, branches: [{empty}, {empty}, {empty}], capstone: \"\", "
                    f"fx: &[{', '.join(f'({FX_KEYS.index(k)}, {f(v)})' for k, v in d['fx'].items())}] }}")
out.append(f"pub const CLASSES: [Class; {len(rows)}] = [{', '.join(rows)}];")
out.append(f"pub const N_BASE_CLASSES: usize = {len(data.CLASSES)};")
out.append("pub const CLASS_WEIGHTS: [&[(usize, f64)]; 4] = [" + ", ".join(
    "&[" + ", ".join(f"({classes.index(c)}, {f(w)})" for c, w in cw.items()) + "]" for cw in data.CLASS_WEIGHTS) + "];")
ATTRS = list(data.ATTRS)
strs("ATTRS", ATTRS)
pers = [t for pair in data.PERSONALITY for t in pair]
strs("PERSONALITY", pers)
out.append("pub const PERSONALITY_FX: [[f64; 6]; %d] = [%s];" % (len(pers), ", ".join(
    "[" + ", ".join(f(data.PERSONALITY_FX.get(t, {}).get(a, 0) + data.PERSONALITY_FX.get(t, {}).get("all", 0))
                    for a in ATTRS) + "]" for t in pers)))
genes = list(data.GENETIC) + ["half-" + a for a in data.ADJ]
strs("GENETIC", genes)
def gfx(t, key):
    return data.GENETIC.get(t, {}).get(key, 1.0 if key == "life" else 0.0)
out.append("pub const GENETIC_FX: [[f64; 9]; %d] = [%s];  // dip mar ste intr lrn lore prowess talent life" % (
    len(genes), ", ".join("[" + ", ".join(f(gfx(t, k)) for k in ATTRS + ["prowess", "talent", "life"]) + "]"
                          for t in genes)))
out.append("pub const GENETIC_FREQ: [(usize, f64); %d] = [%s];" % (len(data.GENETIC_FREQ), ", ".join(
    f"({genes.index(t)}, {f(p)})" for t, p in data.GENETIC_FREQ.items())))
out.append("pub const BLOODLINES: [usize; %d] = [%s];" % (len(data.BLOODLINES), ", ".join(
    str(genes.index(t)) for t in data.BLOODLINES)))
out.append("pub const OPPOSED: [(usize, usize); %d] = [%s];" % (len(data.OPPOSED), ", ".join(
    f"({genes.index(a)}, {genes.index(b)})" for a, b in data.OPPOSED)))
strs("ATTRIBUTES", data2.ATTRIBUTES)
out.append("pub const RACE_ATTR: [[f64; 8]; 4] = [%s];" % ", ".join(
    "[" + ", ".join(f(ra.get(a, 0)) for a in data2.ATTRIBUTES) + "]" for ra in data2.RACE_ATTR))
skills = list(data2.SKILLS)
strs("SKILLS", skills)
out.append("pub const SKILL_GOV: [usize; %d] = [%s];" % (len(skills), ", ".join(
    str(data2.ATTRIBUTES.index(data2.SKILLS[k][0])) for k in skills)))
out.append("pub const RACE_SKILL: [[f64; %d]; 4] = [%s];" % (len(skills), ", ".join(
    "[" + ", ".join(f(rs.get(k, 0)) for k in skills) + "]" for rs in data2.RACE_SKILL)))
out.append("pub const CLASS_SKILLS: [&[usize]; %d] = [%s];" % (len(classes), ", ".join(
    "&[" + ", ".join(str(skills.index(s)) for s in data2.CLASS_SKILLS.get(c, [])) + "]" for c in classes)))
leg = list(data.LEGACY)
strs("LEGACY_KINDS", leg)
strs("LEGACY_NAMES", [data.LEGACY[k][0] for k in leg])
strs("ROMAN", data.ROMAN)
nums("LEGACY_LEVELS", data.LEGACY_LEVELS); nums("HOUSE_LEGACY_LEVELS", data.HOUSE_LEGACY_LEVELS)
nums("LEVEL_CAP_T", [data.LEVEL_CAP, data.BLOOD_LEVEL_CAP])

from realm_of_ages import characters as _ch, arcana as _ar  # noqa: E402
strs("BORROWED", sorted(_ch.BORROWED)); strs("GIFTS", list(_ar.GIFTS)); nums("GIFT_CHANCE", [_ar.GIFT_CHANCE])
out.append("pub const COLORS: [[u8; 3]; 4] = [%s];" % ", ".join("[%d, %d, %d]" % c for c in data.COLORS))
strs("SUCCESSION", data.SUCCESSION)

# ---- power: legacy effects, weapon and school skills, perks
out.append("pub const LEGACY_FX: [&[(&str, f64)]; %d] = [%s];" % (len(data.LEGACY), ", ".join(
    "&[" + ", ".join(f"({rs_str(k)}, {f(v)})" for k, v in fx.items()) + "]" for _, (_, fx) in data.LEGACY.items())))
out.append("pub const WEAPON_SKILL: [usize; %d] = [%s];" % (len(classes), ", ".join(
    str(skills.index(data2.WEAPON_SKILL.get(c, "Blade"))) for c in classes)))
out.append("pub const SCHOOL_SKILL: [usize; 6] = [%s];" % ", ".join(str(skills.index(s)) for s in data2.SCHOOL_SKILL))
out.append("pub const PERKS: [[&str; 5]; %d] = [%s];" % (len(skills), ", ".join(
    "[" + ", ".join(rs_str(p) for p in data2.PERKS[s]) + "]" for s in skills)))
nums("PERK_AT", data2.PERK_AT)
out.append("pub const POWER_GENES: [(&str, &str); %d] = [%s];" % (len(data.POWER_GENES), ", ".join(f"({rs_str(k)}, {rs_str(v)})" for k, v in data.POWER_GENES.items())))

# ---- civics: innovations, regiments, traditions, views
from realm_of_ages import civics as cv  # noqa: E402
NUMK = ["walls_cap", "garrison", "food", "levy", "legit", "corruption", "ships", "material", "research", "crown",
        "wealth", "legacy"]
FLAGK = ["colonize", "feudal", "theocracy", "republic", "admin"]
out.append(f"pub const INNOV_NUM: [&str; {len(NUMK)}] = [{', '.join(rs_str(k) for k in NUMK)}];")
out.append("pub struct Innov { pub name: &'static str, pub era: usize, pub cat: &'static str, pub num: [f64; %d], "
           "pub flags: &'static [&'static str], pub maa: &'static [&'static str] }" % len(NUMK))
rows = []
for era, row in enumerate(cv.INNOVATIONS):
    for n, cat, fx in row:
        num = ", ".join(f(fx.get(k, 0)) for k in NUMK)
        flags = ", ".join(rs_str(k) for k in FLAGK if fx.get(k))
        maa = ", ".join(rs_str(m) for m in fx.get("maa", []))
        rows.append(f"Innov {{ name: {rs_str(n)}, era: {era}, cat: {rs_str(cat)}, num: [{num}], flags: &[{flags}], maa: &[{maa}] }}")
out.append(f"pub const INNOVATIONS: [Innov; {len(rows)}] = [{', '.join(rows)}];")
nums("ERA_COST", cv.COST)
strs("ERAS", cv.ERAS)
out.append("pub const MAA: [(&str, f64, f64); %d] = [%s];" % (len(cv.MAA), ", ".join(f"({rs_str(m)}, {f(p)}, {f(u)})" for m, (p, u) in cv.MAA.items())))
strs("CULTURE_UNIT", cv.CULTURE_UNIT); strs("ETHOS", cv.ETHOS)
out.append("pub const TRADITIONS: [(&str, &[(&str, f64)], [f64; 5]); %d] = [%s];" % (len(cv.TRADITIONS), ", ".join(
    f"({rs_str(t)}, &[{', '.join(f'({rs_str(k)}, {f(v)})' for k, v in fx.items())}], [{', '.join(f(nud.get(a, 0)) for a in cv.AXES)}])"
    for t, (fx, nud) in cv.TRADITIONS.items())))
out.append("pub const CULTURE_VIEWS: [[f64; 5]; 4] = [%s];" % ", ".join("[" + ", ".join(f(v[a]) for a in cv.AXES) + "]" for v in cv.CULTURE_VIEWS))
govs = list(cv.GOV_VIEWS)
strs("GOVS", govs)
out.append("pub const GOV_VIEWS: [[f64; 5]; %d] = [%s];" % (len(govs), ", ".join("[" + ", ".join(f(cv.GOV_VIEWS[g][a]) for a in cv.AXES) + "]" for g in govs)))
strs("GREAT_WORKS", cv.GREAT_WORKS)
from realm_of_ages import resources as _rs  # noqa: E402
strs("CAVALRY", sorted(_rs.CAVALRY))

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "tables.rs"), "w") as fh:
    fh.write("\n".join(out) + "\n")
print(f"wrote src/tables.rs ({len(out)} lines)")
